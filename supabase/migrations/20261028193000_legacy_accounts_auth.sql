begin;

do $$
begin
  if to_regclass('public."Usuario"') is null then
    raise exception 'Tabela public."Usuario" não encontrada; confirme o nome físico antes de aplicar.';
  end if;
  if to_regclass('public."VinculoInstitucional"') is null then
    raise exception 'Tabela public."VinculoInstitucional" não encontrada; confirme o nome físico antes de aplicar.';
  end if;
  if to_regclass('public."Instituicao"') is null then
    raise exception 'Tabela public."Instituicao" não encontrada; confirme o nome físico antes de aplicar.';
  end if;
end $$;

alter table public."Usuario"
  add column if not exists auth_user_id uuid;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where lower(conname) = 'usuario_auth_user_id_fkey'
      and conrelid = 'public."Usuario"'::regclass
  ) then
    alter table public."Usuario"
      add constraint usuario_auth_user_id_fkey
      foreign key (auth_user_id) references auth.users(id) on delete set null;
  end if;
end $$;

create unique index if not exists usuario_auth_user_id_unique
  on public."Usuario" (auth_user_id)
  where auth_user_id is not null;

create unique index if not exists usuario_email_case_insensitive_unique
  on public."Usuario" (lower(email));
do $$

begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'Usuario' and column_name = 'hash_senha'
  ) then
    alter table public."Usuario" alter column hash_senha drop not null;
  end if;
end $$;

alter table public."VinculoInstitucional"
  add column if not exists justificativa text;

create unique index if not exists vinculo_institucional_usuario_instituicao_unique
  on public."VinculoInstitucional" (usuario_id, instituicao_id);

create table if not exists public."AuditoriaIntegracaoContas" (
  id bigint generated by default as identity primary key,
  ator_auth_user_id uuid references auth.users(id) on delete set null,
  ator_usuario_id bigint,
  usuario_alvo_id bigint,
  instituicao_id bigint,
  acao text not null,
  detalhes jsonb not null default '{}'::jsonb,
  criado_em timestamptz not null default now()
);

create index if not exists auditoria_integracao_contas_instituicao_criado_idx
  on public."AuditoriaIntegracaoContas" (instituicao_id, criado_em desc);

alter table public."AuditoriaIntegracaoContas" enable row level security;

create table if not exists public."SolicitacaoExclusaoConta" (
  id bigint generated by default as identity primary key,
  auth_user_id uuid references auth.users(id) on delete set null,
  usuario_id bigint,
  email text not null,
  motivo text not null,
  situacao text not null default 'pendente',
  criado_em timestamptz not null default now(),
  tratado_em timestamptz
);

alter table public."SolicitacaoExclusaoConta" enable row level security;

comment on column public."Usuario".auth_user_id is
  'UUID de auth.users associado ao perfil legado; associar somente após validar a identidade.';
comment on column public."VinculoInstitucional".justificativa is
  'Motivo administrativo de recusa, bloqueio ou revogação do vínculo.';
comment on table public."AuditoriaIntegracaoContas" is
  'Eventos de autenticação e alterações de vínculos executadas pela API legada do sistema.';
comment on table public."SolicitacaoExclusaoConta" is
  'Pedidos LGPD de exclusão de conta; não remove usuário nem histórico automaticamente.';

commit;
